/**
 * Pull the look out of Quire Ink and into the Ghost theme, by RUNNING Quire Ink's own emitters.
 *
 * Nothing here retypes a colour, a size or a rule. `tools/tsconfig.json` maps `@/*` at the
 * sibling checkout, so every value below is the value the live site renders with; when the
 * blog's front end moves, this is re-run rather than re-read. The Quire Ink commit it was
 * taken from is written into the manifest, so a stale copy is a diff and not a guess.
 *
 * Emits, into quire-ink/:
 *   assets/css/quireink-base.css   the hand-written public sheet (PUBLIC_CSS), less the IDE chrome
 *   assets/css/quireink-ide.css    the IDE chrome, so it can be left unloaded when it is off
 *   assets/css/quireink-tokens.css palette + type scale + shape, for DEFAULT_SETTINGS
 *   assets/fonts/*.woff2           the self-hosted faces the default preset can reach
 *   assets/js/core.js, post.js     Quire Ink's own reader bundles, byte for byte
 *   ../tools/extract-manifest.json what came from where, and at which commit
 *
 * WHAT THE WORDPRESS EXTRACTOR EMITS AND THIS ONE DOES NOT, each for a reason:
 *   theme.json   a block-editor dialect. Ghost's editor is Koenig and reads no such file.
 *   editor.css   the same, aimed at a canvas that does not exist here.
 *   rtl.css      WordPress links `rtl.css` from the theme root for an RTL locale with no
 *                code of the theme's. Ghost has no such convention, so the sheet would need
 *                plumbing of its own — ADR 0003.
 *   appearance   ~15 KB of generated PHP for the Customizer. Ghost's theme settings are a
 *                short declarative list in package.json and cannot take a generated table.
 */
