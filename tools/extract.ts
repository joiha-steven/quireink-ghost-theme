/** `backToTop` -> `data-back-to-top`. The inverse of the browser's `dataset` mapping. */
const dataAttr = (key: string) => `data-${key.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}`

function attrs(pairs: [string, string][]): string {
  const seen = new Set<string>()
  const lines: string[] = []
  for (const [key, localeKey] of pairs) {
    if (seen.has(key)) continue
    seen.add(key)
    const value = en[localeKey]
    if (value === undefined) throw new Error(`extract: locales/en.ts has no ${localeKey}`)
    lines.push(` ${dataAttr(key)}="${escapeAttr(value)}"`)
  }
  return lines.join('\n')
}

