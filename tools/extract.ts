// ---------------------------------------------------------------- the words
//
// Every string the two bundles put on screen is read off a `data-` attribute on <body> at
// run time (`layout.ts`'s `Shell.bodyData`), so a bundle carries no locale table. On the
// blog engine the server writes them; a Ghost theme has no server, so they are baked into
// two generated partials here.
//
// GENERATED, not typed. `chromeLabels()` is the engine's own function and the article's
// extra keys are lifted from `article.ts`'s list, so the wording is the wording the blog
// itself ships and a change upstream arrives as a diff on the next extract. Typing them by
// hand is how a theme ends up announcing a button as "button": the bundle's `label()` is
// `dataset[key] ?? ''`, and a key nobody supplies is an empty aria-label rather than a
// missing translation.
const en = t('en') as unknown as Record<string, string>

/**
 * The label KEYS, read out of the engine's source rather than imported from it.
 *
 * `@/web/chrome` cannot be imported: it reaches `@/web/assets`, which imports the built
 * `sw.js`, and that file only exists after the engine's own `build:assets` has run — which
 * this repository must never do, because the engine is read only.
 *
 * So the two lists are PARSED. Every `key: s.something` line inside the function is a label;
 * `defaultScheme: settings.defaultScheme` and the `sw` spread are not, and both fall out for
 * free because neither reads from `s`. A label added upstream arrives on the next extract
 * without anybody noticing it was needed, which is the whole reason this is not a typed list.
 */
async function labelKeys(file: string, from: string, to: string): Promise<[string, string][]> {
  const src = await Bun.file(join(QUIRE, 'src', 'web', file)).text()
  const start = src.indexOf(from)
  if (start < 0) throw new Error(`extract: ${from} is no longer in src/web/${file}`)
  const end = src.indexOf(to, start)
  if (end < 0) throw new Error(`extract: ${to} no longer follows ${from} in src/web/${file}`)
  const block = src.slice(start, end)
  const out: [string, string][] = []
  for (const m of block.matchAll(/(\w+): s\.(\w+)\b/g)) out.push([m[1]!, m[2]!])
  if (out.length === 0) throw new Error(`extract: no labels found in src/web/${file}`)
  return out
}

const chromeKeys = await labelKeys('chrome.ts', 'export function chromeLabels', '\n}')
// The article's own additions. Every `comment*` key is dropped on purpose: Ghost has a
// comment thread of its own and this theme uses it, so the engine's comment island never
// mounts and supplying its strings would put words on the page for machinery that is not
// running.
const postKeys = (await labelKeys('article.ts', 'bodyData: {', 'scripts:'))
