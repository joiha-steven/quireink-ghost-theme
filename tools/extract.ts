// ---------------------------------------------------------------- the alias sheet
//
// Koenig's name for a thing, given the engine's own rule for that thing.
//
// This started life in `ghost-bridge.js`, adding Quire Ink's class beside Ghost's on the way
// past — the trick the WordPress port plays in a `render_block` filter. It was wrong here for
// a reason gscan said out loud: `.kg-width-wide` and `.kg-width-full` have to appear STYLED
// in a Ghost theme's CSS, and behind that rule is a reader with no JavaScript, for whom a
// wide figure was simply not wide. A layout that needs a script to be a layout is not one.
//
// So the rules are DERIVED instead. The engine's own declarations are lifted verbatim out of
// `PUBLIC_CSS` and re-emitted under Koenig's selector: one definition of what "wide" means,
// still upstream, and a re-extract carries any change across without anyone re-reading this.
//
// Each is scoped under `.prose` so it is 0,2,0 and outranks Ghost's own `.kg-*` card sheet,
// which `{{ghost_head}}` injects after everything this theme links.
const ALIASES: [string, string[]][] = [
  ['.img-wide', ['.kg-width-wide', '.kg-width-full']],
  ['.callout', ['.kg-callout-card']],
]

/**
 * Split a selector list on its TOP-LEVEL commas only.
 *
 * `.prose > :is(figure.img-wide,.video-wide):nth-child(-n+2)` is ONE selector with a comma
 * inside it. Split naively it becomes two fragments with unmatched parentheses, and a browser
 * silently drops a rule whose selector will not parse — so the rule is simply absent and
 * nothing anywhere says so.
 */
function splitSelectors(list: string): string[] {
  const out: string[] = []
  let depth = 0
  let current = ''
  for (const ch of list) {
    if (ch === '(' || ch === '[') depth++
    else if (ch === ')' || ch === ']') depth--
    if (ch === ',' && depth === 0) { out.push(current); current = ''; continue }
    current += ch
  }
  out.push(current)
  return out.map((x) => x.trim()).filter(Boolean)
}

function aliasSheet(sheet: string): { css: string; count: number } {
  // Comments first, and not as tidiness: the engine's sheet carries prose comments with
  // `.prose` and `.callout` inside them, and a selector regex run over the raw text pulled
  // half a sentence into a stylesheet. It parsed, it matched nothing, and it was visible only
  // by reading the generated file.
  const clean = sheet.replace(/\/\*[\s\S]*?\*\//g, '')

  const out: string[] = []
  let count = 0

  // At-rules are kept as CONTEXT rather than flattened. A rule that only applies inside a
  // media query, re-emitted without it, applies everywhere — which is a layout that is right
  // at one width and wrong at every other, and nothing about it looks wrong in a diff.
  const scan = (css: string, wrap: string[]): void => {
    const rule = /(@[a-z-]+[^{;]*)\{|([^{}@]+)\{([^{}]*)\}/gi
    let m: RegExpExecArray | null
    while ((m = rule.exec(css)) !== null) {
      if (m[1] !== undefined) {
        // An at-rule: find its matching brace and recurse with the condition pushed on.
        let depth = 1
        let i = rule.lastIndex
        while (i < css.length && depth > 0) {
          if (css[i] === '{') depth++
          else if (css[i] === '}') depth--
          i++
        }
        scan(css.slice(rule.lastIndex, i - 1), [...wrap, m[1]!.trim()])
        rule.lastIndex = i
        continue
      }
      const decls = (m[3] ?? '').trim()
      if (!decls) continue
      for (const [from, tos] of ALIASES) {
        const token = new RegExp(from.replace('.', '\\.') + '(?![\\w-])')
        const parts = splitSelectors(m[2]!).filter((x) => token.test(x))
        if (parts.length === 0) continue
        for (const to of tos) {
          const selectors = parts
            .map((x) => x.replace(new RegExp(token.source, 'g'), to))
            .map((x) => (x.includes('.prose') ? x : `.prose ${x}`))
          const body = `${selectors.join(',')}{${decls}}`
          out.push(wrap.length ? `${wrap.join('{')}{${body}${'}'.repeat(wrap.length)}` : body)
          count++
        }
      }
    }
  }

  scan(clean, [])
  return { css: out.join('\n'), count }
}

